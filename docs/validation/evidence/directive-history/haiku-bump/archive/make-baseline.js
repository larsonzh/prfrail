'use strict';
// Materialize the review-input baseline for the ⑦ re-review of DIRECTIVE-HAIKU-BUMP.
// ⑦'s carrier has read/search tools only (no command execution), so the baseline comparison must be
// delivered as TEXT it can read and compare itself: for every frozen region we print the HEAD text
// and the worktree text side by side, plus the two text-level claims (the OB-74 row, the §7.2.3
// first paragraph), plus the region hashes measured by the driver.
const { execSync } = require('child_process');
const fs = require('fs');
const crypto = require('crypto');

const OUT = 'tmp/haiku-bump/head-baseline.txt';
const FILES = ['docs/DELIVERY_DIRECTIVE.md', 'docs/DELIVERY_DIRECTIVE_EN.md'];
const sha = (s) => crypto.createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 16);

const seg = (text, a, b) => {
  const lines = text.split('\n');
  const i = lines.findIndex((l) => l.startsWith(a));
  const j = lines.findIndex((l, k) => k > i && l.startsWith(b));
  if (i < 0 || j < 0) return null;
  return lines.slice(i, j).join('\n');
};

const out = [];
out.push('# ⑦ review-input baseline (generated by the driver, ' + new Date().toISOString() + ')');
out.push('# Purpose: let the ⑦ reviewer compare HEAD vs worktree TEXTUALLY with read-only tools.');
out.push('# Every region below is printed twice (HEAD, then WORKTREE). Zero diff == the two blocks are identical.');
out.push('');

for (const f of FILES) {
  const isEn = /_EN\.md$/.test(f);
  const head = execSync('git show HEAD:' + f, { maxBuffer: 1 << 28 }).toString('utf8').replace(/\r\n/g, '\n');
  const work = fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  const regions = [
    ['2.2 closed set', '### 2.2 ', '### 2.3 '],
    ['2.4 wording', '### 2.4 ', '### 2.5 '],
    ['6.3 criteria', '### 6.3 ', '### 6.4 '],
    ['7.5 cost table', '### 7.5 ', '### 7.6 '],
    ['appendix B', isEn ? '## Appendix B' : '## 附录 B', isEn ? '## Appendix C' : '## 附录 C'],
  ];
  out.push('################################################################################');
  out.push('FILE: ' + f);
  out.push('################################################################################');
  for (const [name, a, b] of regions) {
    const hs = seg(head, a, b);
    const ws = seg(work, a, b);
    out.push('');
    out.push('===== REGION: ' + name + ' =====');
    out.push('HEAD sha16=' + (hs === null ? 'MISSING' : sha(hs)) + ' lines=' + (hs === null ? '-' : hs.split('\n').length));
    out.push('WORK sha16=' + (ws === null ? 'MISSING' : sha(ws)) + ' lines=' + (ws === null ? '-' : ws.split('\n').length));
    out.push('IDENTICAL=' + (hs !== null && ws !== null && hs === ws));
    out.push('--- HEAD TEXT ---');
    out.push(hs === null ? '(missing)' : hs);
    out.push('--- WORKTREE TEXT ---');
    out.push(ws === null ? '(missing)' : ws);
  }
  // text-level claims ⑦ must verify literally
  const rowOf = (text, needle) => text.split('\n').find((l) => l.includes(needle)) || '(not found)';
  const para = (text) => {
    const lines = text.split('\n');
    const i = lines.findIndex((l) => l.startsWith('### 7.2.3 '));
    return lines.slice(i + 1).find((l) => l.trim() !== '') || '(not found)';
  };
  out.push('');
  out.push('===== TEXT CLAIM 1: the OB-74 ledger row (domain: phenomenon column must be untouched) =====');
  out.push('--- HEAD ROW ---');
  out.push(rowOf(head, '| OB-74 |'));
  out.push('--- WORKTREE ROW ---');
  out.push(rowOf(work, '| OB-74 |'));
  out.push('');
  out.push('===== TEXT CLAIM 2: the §7.2.3 first paragraph (domain: only the version string changed) =====');
  out.push('--- HEAD PARA ---');
  out.push(para(head));
  out.push('--- WORKTREE PARA ---');
  out.push(para(work));
}
out.push('');
out.push('# END OF BASELINE');
fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log('wrote ' + OUT + ' lines=' + out.length);
